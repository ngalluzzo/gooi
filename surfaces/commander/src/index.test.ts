import { describe as group, expect, test } from "bun:test";
import { edge, invoke } from "@gooi/exchange";
import { artifact, artifactId } from "@gooi/kernel/evidence";
import { parsesTo } from "@gooi/estree";
import {
  COMMAND_TREE,
  compile,
  describe,
  lowerToEstree,
  type Layout,
} from "./index.js";

const IN = { id: "urn:test:in", version: 1 };
const OUT = { id: "urn:test:out", version: 1 };
const fake = (inputSchema?: object) =>
  edge(
    {
      operation: { input: IN, output: OUT },
      ...(inputSchema ? { inputSchema: inputSchema as never } : {}),
      claim: { id: "urn:test:applied", version: 1 },
      scope: "Test",
    },
    () => ({}),
  );
const add = fake({
  description: "Add a thing",
  type: "object",
  properties: {
    title: { type: "string", description: "Its title" },
    notes: { type: "string", description: "Extra notes" },
  },
  required: ["title"],
  additionalProperties: false,
});
const list = fake({ description: "List things", type: "object", properties: {} });
const layout: Layout = {
  thing: { description: "Things", commands: { add, list } },
  status: list,
};
const program = { name: "app", description: "An app", module: "./layout.js", export: "layout" };

group("describe", () => {
  test("turns a layout of edges into a command tree", () => {
    expect(describe(layout, program)).toEqual({
      ...program,
      commands: [
        {
          kind: "group",
          name: "thing",
          description: "Things",
          commands: [
            {
              kind: "command",
              name: "add",
              description: "Add a thing",
              path: ["thing", "commands", "add"],
              options: [
                { field: "title", description: "Its title", required: true },
                { field: "notes", description: "Extra notes", required: false },
              ],
            },
            {
              kind: "command",
              name: "list",
              description: "List things",
              path: ["thing", "commands", "list"],
              options: [],
            },
          ],
        },
        { kind: "command", name: "status", description: "List things", path: ["status"], options: [] },
      ],
    });
  });

  test("refuses what Commander cannot express", () => {
    expect(() => describe({ x: fake() }, program)).toThrow("x: Commander needs an object input schema");
    const numeric = fake({ type: "object", properties: { n: { type: "number" } } });
    expect(() => describe({ x: numeric }, program)).toThrow("x --n: Commander options here are strings");
    expect(() => describe({ "Bad-Name": list }, program)).toThrow("names are lowercase");
    expect(() => describe({ help: list }, program)).toThrow('not "help"');
    expect(() => describe({ x: { nope: true } } as never, program)).toThrow("expected an edge or a");
  });
});

group("lowering", () => {
  test("lowers through ESTree to source that parses back to the program", async () => {
    const { tree, program: estree, source, traces } = await compile(layout, program);
    expect(source).toContain(`// Generated by @gooi/commander from command tree ${artifactId(tree)}.`);
    expect(source).toContain('import { layout } from "./layout.js";');
    expect(source).not.toContain("@gooi/cli");
    expect(source).toContain('.requiredOption("--title <title>", "Its title")');
    expect(source).toContain('.option("--notes <notes>", "Extra notes")');
    expect(source).toContain("run(layout.thing.commands.add, { ...options })");
    expect(source).toContain("run(layout.status, { ...options })");
    expect(parsesTo(source, estree.value as never)).toBe(true);
    expect(traces).toHaveLength(1);
    expect(traces[0]).toMatchObject({ verdict: "passed", missingStage: null });
    expect(traces[0]!.claims).toHaveLength(2);
  });

  test("refuses hostile trees before any code exists", async () => {
    const tree = (patch: object) =>
      artifact(COMMAND_TREE, { ...program, commands: [], ...patch });
    for (const [patch, problem] of [
      [{ module: "./ok.js\nawait import('node:child_process')" }, "module must match pattern"],
      [{ description: "line one\nline two" }, "description must match pattern"],
      [{ export: "default" }, "A reserved word can't name a binding: default"],
    ] as const)
      await expect(invoke(lowerToEstree, tree(patch))).rejects.toThrow(problem);
    const twice = tree({
      commands: [
        { kind: "command", name: "x", description: "", path: ["x"], options: [] },
        { kind: "command", name: "x", description: "", path: ["y"], options: [] },
      ],
    });
    await expect(invoke(lowerToEstree, twice)).rejects.toThrow('Two commands named "x"');
    const partial = tree({ commands: [{ kind: "command", name: "x" }] });
    await expect(invoke(lowerToEstree, partial)).rejects.toThrow();
  });
});
