import { describe as group, expect, test } from "bun:test";
import { edge, invoke } from "@gooi/exchange";
import { artifact, artifactId } from "@gooi/kernel/evidence";
import { parsesTo } from "@gooi/estree";
import { ROUTE_TREE, compile, describe, lowerToEstree, type Routes } from "./index.js";

const A = { id: "urn:test:a", version: 1 };
const B = { id: "urn:test:b", version: 1 };
const HTML = { id: "https://www.iana.org/assignments/media-types/text/html", version: 1 };
const step = (input: typeof A, output: typeof A, inputSchema?: object) =>
  edge(
    {
      operation: { input, output },
      ...(inputSchema ? { inputSchema: inputSchema as never } : {}),
      claim: { id: "urn:test:step", version: 1 },
      scope: "Test",
    },
    () => ({}),
  );
const query = { type: "object", properties: { q: { type: "string" } } };
const routes: Routes = {
  page: { path: "/", steps: [step(A, B, query), step(B, HTML)] },
  data: { path: "/data/raw", steps: [step(A, B, query)] },
};
const server = { module: "./routes.js", export: "routes" };

group("describe", () => {
  test("reads connected paths of edges and what they serve", () => {
    expect(describe(routes, server)).toEqual({
      ...server,
      routes: [
        { name: "page", path: "/", media: "text/html" },
        { name: "data", path: "/data/raw", media: null },
      ],
    });
  });

  test("refuses routes that aren't connected paths", () => {
    const cases: [Routes, string][] = [
      [{ x: { path: "/", steps: [step(A, B, query), step(A, B)] } }, "x: step 2 takes urn:test:a@1 but step 1 gives urn:test:b@1"],
      [{ x: { path: "/", steps: [] } }, "x: a route needs at least one edge"],
      [{ x: { path: "/", steps: [step(A, B)] } }, "x: the first edge needs an object input schema"],
      [{ x: { path: "/<script>", steps: [step(A, B, query)] } }, "x path"],
      [
        { x: { path: "/", steps: [step(A, B, query)] }, y: { path: "/", steps: [step(A, B, query)] } },
        "Two routes serve /",
      ],
    ];
    for (const [layout, problem] of cases) expect(() => describe(layout, server)).toThrow(problem);
  });
});

group("lowering", () => {
  test("lowers through ESTree to a Hono app that parses back", async () => {
    const { tree, program, source, traces } = await compile(routes, server);
    expect(source).toContain(`// Generated by @gooi/hono from route tree ${artifactId(tree)}.`);
    expect(source).toContain('import { routes } from "./routes.js";');
    expect(source).toContain('app.get("/", async (c) =>');
    expect(source).toContain("await run(routes.page.steps, c.req.query())");
    expect(source).toContain('"content-type": "text/html; charset=utf-8"');
    expect(source).toContain('"content-type": "application/json; charset=utf-8"');
    expect(source).toContain("error instanceof InputError ? 400 : 500");
    expect(source).toContain("export default app;");
    expect(parsesTo(source, program.value as never)).toBe(true);
    expect(traces[0]).toMatchObject({ verdict: "passed", missingStage: null });
  });

  test("refuses hostile trees before any code exists", async () => {
    const tree = (patch: object) => artifact(ROUTE_TREE, { ...server, routes: [], ...patch });
    for (const [patch, problem] of [
      [{ module: "./ok.js\nawait import('x')" }, "module must match pattern"],
      [{ export: "default" }, "A reserved word can't name a binding: default"],
      [{ routes: [{ name: "x", path: "/a b", media: null }] }, "path must match pattern"],
      [{ routes: [{ name: "x", path: "/", media: "text/html; evil" }] }, "media must match pattern"],
    ] as const)
      await expect(invoke(lowerToEstree, tree(patch))).rejects.toThrow(problem);
  });
});
